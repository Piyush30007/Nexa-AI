import React from 'react'

function cls(userClass, defaultClass = 'w-4 h-4') {
  if (!userClass) return `${defaultClass} shrink-0`
  const hasW = /\bw-\S+/.test(userClass)
  const hasH = /\bh-\S+/.test(userClass)
  let res = userClass
  if (!hasW && !hasH) res = `${defaultClass} ${userClass}`
  if (!res.includes('shrink-0')) res = `${res} shrink-0`
  return res
}

